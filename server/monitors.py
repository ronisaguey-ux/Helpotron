"""Persistent health monitors: traffic, activity, data lake, cost.

Runs inside the FastAPI process. Three pieces:

1. MonitorMiddleware — counts every HTTP request (method + endpoint
   template + status code) into in-memory counters. Aggregate only: no
   user ids, no raw payloads, no IPs.
2. run_monitors_loop() — background task started from the app lifespan.
   Every MONITORS_INTERVAL seconds it snapshots: traffic rates, data lake
   file row counts(+deltas), DB activity counts (study sessions, materials,
   transcripts, assignments) and API cost totals (api_usage_logs).
   Snapshots are appended to data_lake/monitors_history.jsonl (persists
   across restarts; trimmed to the last 2000).
3. get_live_snapshot() / get_history() — what /api/monitors/* serve.
"""
from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import re
import threading
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from fastapi import Request
from starlette.middleware.base import BaseHTTPMiddleware
from starlette.responses import Response

from .database import SessionLocal, Assignment, StudyMaterial, StudySession, Transcript, ApiUsageLog
from .datalake import DATALAKE_DIR, TELEMETRY_DIR, FEEDBACK_DIR, CORPUS_DIR

logger = logging.getLogger("monitors")

MONITORS_INTERVAL = 60  # seconds between history snapshots
HISTORY_FILE = DATALAKE_DIR / "monitors_history.jsonl"
HISTORY_MAX_LINES = 2000

# ── live request counters (aggregate only) ──────────────────────────────────
_lock = threading.Lock()
_started_ts = time.time()
_req_total = 0
_req_by_path: Dict[str, int] = {}
_req_by_status: Dict[int, int] = {}
_last_snapshot: Dict[str, Any] = {}
_last_snapshot_ts: Optional[float] = None
_snap_requests = 0  # REAL (user) requests since last snapshot — drives the rate
_user_requests = 0   # lifetime real requests
_poll_requests = 0   # lifetime session-polling requests (an open tab's timers)
_bg_requests = 0     # lifetime probes / self-observation / preflight / assets

# ── what counts as REAL traffic (owner 2026-09-19) ──────────────────────────
#
# The middleware used to count every request, which made the "Live API Traffic"
# number meaningless. Measured on the live box before this fix, out of 4,494
# lifetime requests:
#
#    1086  GET /api/user/admin-notices   <-- an open tab polling itself
#    1084  GET /api/me                   <-- same
#    1081  GET /api/health               <-- infrastructure probe
#    1075  GET /api/notifications        <-- same
#     112  GET /api/extension/version
#       7  GET /api/monitors/overview    <-- the monitor observing itself
#
# That is ~96% NOT user traffic. Two consequences the owner saw as "fake data":
# leaving a dashboard open RAISED the traffic graph (self-observation), and the
# handful of real user actions were invisible underneath the noise.
#
# So requests are classified. Nothing is hidden: excluded requests are still
# counted, in `background`, and reported alongside — the headline number is just
# no longer a lie.
#
# Infrastructure probes: liveness only, not a person doing anything.
_NOISE_PATHS = {
    "/api/health", "/health", "/healthz", "/api/ping", "/favicon.ico",
}
# Self-observation: counting these makes the graph rise because you are looking
# at it. Classic observer effect, and it is not traffic.
_MONITOR_PATHS_PREFIX = ("/api/monitors",)
# Session polling: real requests, but generated by an idle open tab on a timer
# rather than by a person acting. Kept visible, excluded from the rate.
_POLLING_PATHS = {
    "/api/me", "/api/notifications", "/api/user/admin-notices",
    "/api/extension/version", "/api/extension/releases",
}


def _classify_request(method: str, path: str) -> str:
    """Return 'user' | 'polling' | 'background'.

    'user' is the only bucket that feeds the traffic rate.
    """
    if method == "OPTIONS":
        # CORS preflight is the browser talking to itself, never a user action.
        return "background"
    p = path or ""
    if p in _NOISE_PATHS:
        return "background"
    if any(p.startswith(pre) for pre in _MONITOR_PATHS_PREFIX):
        return "background"
    # Anything that is not an API call is an asset/route load, not measured
    # traffic (the SPA shell and its bundles).
    if not p.startswith("/api/"):
        return "background"
    if p in _POLLING_PATHS:
        return "polling"
    return "user"


def _template_path(path: str) -> str:
    """Collapse numeric path segments so /assignments/123 and /assignments/456
    count into one endpoint line."""
    segments = re.split(r"/", path)
    norm = []
    for s in segments:
        if s.isdigit() and len(s) < 16:
            s = "{id}"
        norm.append(s)
    return "/".join(norm)


class MonitorMiddleware(BaseHTTPMiddleware):
    """Count requests, split into REAL traffic and background noise.

    Only 'user' requests feed the traffic rate. 'polling' (an open tab's own
    timers) and 'background' (health probes, the monitor's own endpoints, CORS
    preflight, assets) are counted separately and still reported, so nothing is
    silently dropped — but the headline figure means something.
    """

    async def dispatch(self, request: Request, call_next):
        global _req_total, _snap_requests, _user_requests, _poll_requests, _bg_requests
        route = getattr(request.scope.get("route"), "path", None)
        path = _template_path(route or request.url.path)
        method = request.method
        try:
            response: Response = await call_next(request)
        except Exception:
            status = 500
            raise
        else:
            status = response.status_code
        bucket = _classify_request(method, path)
        with _lock:
            _req_total += 1
            if bucket == "user":
                # The ONLY counter that drives the reported traffic rate.
                _snap_requests += 1
                _user_requests += 1
                key = f"{method} {path}"
                _req_by_path[key] = _req_by_path.get(key, 0) + 1
                _req_by_status[status] = _req_by_status.get(status, 0) + 1
            elif bucket == "polling":
                _poll_requests += 1
            else:
                _bg_requests += 1
        return response


# ── count helpers ───────────────────────────────────────────────────────────
def _count_lines(path: Path) -> int:
    try:
        if not path.exists():
            return 0
        return sum(1 for _ in path.open("r", encoding="utf-8"))
    except Exception:
        return 0


def _count_distinct_events(path: Path) -> Dict[str, int]:
    """Count telemetry by DISTINCT payload, not raw lines.

    Owner 2026-09-19: *"it counts fake test entries as real, make it only count
    legit traffic/events"*.

    Measured on the live lake before this fix: `operational_events.jsonl` held
    814 rows but only **328 distinct payloads** — 193 byte-identical
    `assignment_evasion` records and 193 identical `gdocs_export` records,
    written ~10 s apart across days from three user hashes, with identical
    scores (82.0 -> 12.0, burstiness 34.5). Those are a synthetic load run, not
    814 things that happened, and the dashboard showed them as real activity.

    A repeated payload with the event id and timestamp stripped is the honest
    signal for that. Two REAL events cannot produce identical metrics to the
    last decimal — a genuine humanization run varies every time — so collapsing
    them loses nothing and stops the count from being inflated.

    Returns {"rows", "distinct", "synthetic"} so the raw figure stays visible.
    """
    rows = 0
    sigs = set()
    try:
        if not path.exists():
            return {"rows": 0, "distinct": 0, "synthetic": 0}
        with path.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                rows += 1
                try:
                    obj = json.loads(line)
                except Exception:
                    # Unparseable line: count it as its own distinct event rather
                    # than silently merging it into something else.
                    sigs.add(line)
                    continue
                payload = obj.get("data") if isinstance(obj, dict) and "data" in obj else obj
                if isinstance(payload, dict):
                    # Drop volatile identity/timing so only the MEASURED values
                    # decide whether two records are the same event.
                    stable = {k: v for k, v in payload.items()
                              if k not in ("user_id", "public_id", "session_id",
                                           "user_hash", "document_id", "event_id",
                                           "timestamp")}
                else:
                    stable = payload
                sigs.add(hashlib.sha256(
                    json.dumps(stable, sort_keys=True, default=str).encode()
                ).hexdigest())
    except Exception as e:
        logger.error("distinct event count failed for %s: %s", path, e)
        return {"rows": 0, "distinct": 0, "synthetic": 0}
    return {"rows": rows, "distinct": len(sigs), "synthetic": max(0, rows - len(sigs))}


def _datalake_counts() -> Dict[str, int]:
    ev = _count_distinct_events(TELEMETRY_DIR / "operational_events.jsonl")
    return {
        # `operational_events` is the DISTINCT count — what the dashboard shows.
        # The raw row count stays available as `operational_events_rows`, so the
        # excluded volume is visible instead of hidden.
        "operational_events": ev["distinct"],
        "operational_events_rows": ev["rows"],
        "operational_events_synthetic": ev["synthetic"],
        "user_feedback": _count_lines(FEEDBACK_DIR / "user_feedback.jsonl"),
        "humanized_samples": _count_lines(CORPUS_DIR / "humanized_samples.jsonl"),
        "microcredit_submissions": _count_lines(DATALAKE_DIR / "microcredit_submissions.jsonl"),
    }


def _activity_counts() -> Dict[str, int]:
    """DB row counts (totals + last 24 h) — the site's real usage signals."""
    since = datetime.now(timezone.utc) - timedelta(hours=24)
    try:
        db = SessionLocal()
        try:
            def cnt(model, since_col=None):
                q = db.query(model)
                if since_col is not None:
                    q = q.filter(since_col >= since)
                return q.count()
            return {
                "study_sessions": cnt(StudySession),
                "study_sessions_24h": cnt(StudySession, StudySession.created_at),
                "study_materials": cnt(StudyMaterial),
                "transcripts": cnt(Transcript),
                "assignments": cnt(Assignment),
                "assignments_24h": cnt(Assignment, Assignment.created_at),
            }
        finally:
            db.close()
    except Exception as e:
        logger.error("activity count failed: %s", e)
        return {}


def _cost_counts() -> Dict[str, Any]:
    """API cost totals from api_usage_logs (charged USD + tokens)."""
    since = datetime.now(timezone.utc) - timedelta(hours=24)
    try:
        from sqlalchemy import func
        db = SessionLocal()
        try:
            row = db.query(
                func.coalesce(func.sum(ApiUsageLog.charged_cost_usd), 0.0),
                func.coalesce(func.sum(ApiUsageLog.input_tokens), 0),
                func.coalesce(func.sum(ApiUsageLog.output_tokens), 0),
                func.count(ApiUsageLog.id),
            ).one()
            row24 = db.query(
                func.coalesce(func.sum(ApiUsageLog.charged_cost_usd), 0.0),
                func.count(ApiUsageLog.id),
            ).filter(ApiUsageLog.created_at >= since).one()
            return {
                "cost_usd": round(float(row[0]), 4),
                "cost_usd_24h": round(float(row24[0]), 4),
                "calls": int(row[3]),
                "calls_24h": int(row24[1]),
                "input_tokens": int(row[1]),
                "output_tokens": int(row[2]),
            }
        finally:
            db.close()
    except Exception as e:
        logger.error("cost count failed: %s", e)
        return {}


def _deltas(cur: Dict[str, int], prev: Dict[str, int]) -> Dict[str, int]:
    """Per-key delta between two counter dicts (entries ingested since last
    snapshot)."""
    return {k: max(0, cur.get(k, 0) - prev.get(k, 0)) for k in cur}


def _snapshot() -> Dict[str, Any]:
    with _lock:
        total = _req_total
        snap_reqs = _snap_requests
        by_path = dict(_req_by_path)
        by_status = dict(_req_by_status)
        user_total = _user_requests
        poll_total = _poll_requests
        bg_total = _bg_requests
    prev = _last_snapshot.get("traffic", {}) if _last_snapshot else {}
    dl_now = _datalake_counts()
    dl_prev = _last_snapshot.get("datalake_counts", {}) if _last_snapshot else {}
    top = sorted(by_path.items(), key=lambda kv: -kv[1])[:10]
    return {
        "ts": datetime.now(timezone.utc).isoformat(),
        "uptime_seconds": int(time.time() - _started_ts),
        "traffic": {
            # `total_requests` / `requests_last_window` / the rate / the endpoint
            # table / the status split are ALL real user traffic only (owner
            # 2026-09-19). `all_requests` carries the raw lifetime count so the
            # excluded volume is still visible rather than hidden.
            "total_requests": user_total,
            "requests_last_window": snap_reqs,
            "requests_per_min": round(snap_reqs / (MONITORS_INTERVAL / 60), 2),
            "top_endpoints": [{"endpoint": k, "count": v} for k, v in top],
            "status_counts": {str(k): v for k, v in sorted(by_status.items())},
            # Excluded volume, kept visible. The UI shows this as "N background
            # requests not counted" rather than letting the number vanish.
            "excluded": {
                "all_requests": total,
                "session_polling": poll_total,
                "background": bg_total,
                "note": "health probes, the monitor's own endpoints, CORS preflight "
                        "and an idle tab's session polling are excluded from the rate",
            },
        },
        "datalake_counts": dl_now,
        "datalake": {**dl_now, "deltas_last_window": _deltas(dl_now, dl_prev)},
        "activity": _activity_counts(),
        "cost": _cost_counts(),
    }


_snapshot_count = 0


def _persist(snap: Dict[str, Any]) -> None:
    global _snapshot_count
    try:
        DATALAKE_DIR.mkdir(parents=True, exist_ok=True)
        with HISTORY_FILE.open("a", encoding="utf-8") as f:
            f.write(json.dumps(snap, ensure_ascii=False) + "\n")
        _snapshot_count += 1
        if _snapshot_count % 30 == 0:
            _trim_history()
    except Exception as e:
        logger.error("persist snapshot failed: %s", e)


def _trim_history() -> None:
    try:
        lines = HISTORY_FILE.read_text(encoding="utf-8").splitlines()
        if len(lines) > HISTORY_MAX_LINES:
            HISTORY_FILE.write_text("\n".join(lines[-HISTORY_MAX_LINES:]) + "\n", encoding="utf-8")
    except Exception:
        pass


async def run_monitors_loop() -> None:
    """Background task (lifespan-managed): snapshot every MONITORS_INTERVAL.

    Also the host for periodic IDLE RECLAMATION — freeing a loaded-but-unused model is the
    same kind of housekeeping as taking a snapshot, and it needs a tick on a running server.

    ★ WHY HERE AND NOT IN THE ADMISSION PATH. Reclamation only has to happen when a new user
    needs room, but doing it inside `run_with_budget` would make a request wait on
    `systemctl` (seconds) before it could even queue. This loop runs every
    MONITORS_INTERVAL, and `release_idle_models()` is a NO-OP unless there is genuine memory
    pressure, so an idle box with headroom keeps its models warm.
    """
    global _last_snapshot, _last_snapshot_ts, _snap_requests
    await asyncio.to_thread(snapshot_once)
    while True:
        await asyncio.sleep(MONITORS_INTERVAL)
        await asyncio.to_thread(snapshot_once)
        try:
            from .resource_guard import release_idle_models
            released = await asyncio.to_thread(release_idle_models)
            if released:
                logger.warning("idle reclamation freed %s", ", ".join(released))
        except Exception as e:                                    # noqa: BLE001
            # Reclamation is an optimisation. Never let it take the monitor loop, and with
            # it every snapshot the admin dashboard reads, down with it.
            logger.debug("idle reclamation skipped: %s", e)


def snapshot_once() -> Dict[str, Any]:
    """Take + persist one snapshot, also usable synchronously (tests)."""
    global _last_snapshot, _last_snapshot_ts, _snap_requests
    snap = _snapshot()
    _persist(snap)
    _last_snapshot = snap
    _last_snapshot_ts = time.time()
    with _lock:
        _snap_requests = 0
    return snap


def get_live_snapshot() -> Dict[str, Any]:
    """Live counters + the most recent persisted snapshot."""
    live = _snapshot()
    live["last_snapshot_ts"] = _last_snapshot_ts
    live["live"] = True
    return live


def get_history(limit: int = 100) -> List[Dict[str, Any]]:
    try:
        if not HISTORY_FILE.exists():
            return []
        lines = HISTORY_FILE.read_text(encoding="utf-8").splitlines()
        out = []
        for line in lines[-limit:]:
            line = line.strip()
            if line:
                try:
                    out.append(json.loads(line))
                except Exception:
                    continue
        return out
    except Exception:
        return []
