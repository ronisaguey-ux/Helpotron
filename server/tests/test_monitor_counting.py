def test_distinct_event_count_collapses_repeated_payloads(tmp_path: Path):
    """A synthetic run repeats one payload; a real run varies every time."""
    import json

    f = tmp_path / "ev.jsonl"
    rows = []
    # 50 copies of ONE payload, differing only by id/timestamp — as a load run
    # actually writes them.
    for i in range(50):
        rows.append({
            "event_id": f"evt_{i}", "event_type": "assignment_evasion",
            "timestamp": f"2026-08-17T18:20:{i:02d}+00:00",
            "data": {"word_count": 550, "initial_ai_score": 82.0,
                     "final_ai_score": 12.0, "burstiness": 34.5,
                     "user_hash": "usr_22bf17b897c2"},
        })
    # 3 genuinely different events.
    for i, wc in enumerate([120, 300, 900]):
        rows.append({
            "event_id": f"real_{i}", "event_type": "assignment_evasion",
            "timestamp": "2026-09-07T00:00:00+00:00",
            "data": {"word_count": wc, "initial_ai_score": 70.0 + i,
                     "final_ai_score": 10.0 + i, "burstiness": 20.0 + i},
        })
    f.write_text("\n".join(json.dumps(r) for r in rows), encoding="utf-8")

    out = _count_distinct_events(f)
    assert out["rows"] == 53
    assert out["distinct"] == 4, "50 identical payloads must collapse to 1"
    assert out["synthetic"] == 49


def test_distinct_event_count_treats_unparseable_lines_as_their_own(tmp_path: Path):
    """A malformed line is not silently merged into anything else."""
    f = tmp_path / "ev.jsonl"
    f.write_text("not json\n{\"data\": {\"a\": 1}}\n", encoding="utf-8")
    out = _count_distinct_events(f)
    assert out["rows"] == 2
    assert out["distinct"] == 2
    assert out["synthetic"] == 0


def test_missing_file_counts_as_zero(tmp_path: Path):
    out = _count_distinct_events(tmp_path / "nope.jsonl")
    assert out == {"rows": 0, "distinct": 0, "synthetic": 0}
